const escape=text=>String(text).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const tags={row:'mrow',frac:'mfrac',pow:'msup',root:'msqrt',sub:'msub',nthRoot:'mroot'};
export function mathMarkup(node){
  if(typeof node==='string')return `<mtext>${escape(node)}</mtext>`;
  const tag=tags[node.kind];
  if(!tag)throw new Error('Unknown formula node');
  return `<${tag}>${node.args.map(mathMarkup).join('')}</${tag}>`;
}
export function mathText(node){
  if(typeof node==='string')return node;
  const args=node.args.map(mathText);
  if(node.kind==='frac')return `（${args[0]}）除以（${args[1]}）`;
  if(node.kind==='pow')return `（${args[0]}）的（${args[1]}）次方`;
  if(node.kind==='root')return `根號（${args[0]}）`;
  if(node.kind==='nthRoot')return `（${args[0]}）的 ${args[1]} 次根`;
  if(node.kind==='sub')return `${args[0]} 下標 ${args[1]}`;
  return args.join('');
}
